/* Auto gallery carousel loader
   Usage (on a project page):
     <div id="auto-gallery" data-folder="../images/projects/8. TAMS360"></div>

   Requirements:
   - Each images folder contains a _list.json (generated by your PowerShell script)
   - Works with folder/file names containing spaces
   - Handles UTF-8 BOM in _list.json (common on Windows)

   Note:
   - Browsers block fetch() on file://. Use a server (python -m http.server) or GitHub Pages.
*/
(function () {
  function encPath(p) {
    // Encode each segment so folders with spaces work (../images/projects/6. ProVisio - App)
    return p.split('/').map(encodeURIComponent).join('/');
  }

  function stripBOM(s) {
    return s && s.charCodeAt(0) === 0xFEFF ? s.slice(1) : s;
  }

  function buildCarousel(el, folder, files) {
    const id = 'carousel-' + Math.random().toString(36).slice(2);
    const base = encPath(folder);

    const inner = files.map((name, i) => `
      <div class="carousel-item ${i === 0 ? 'active' : ''}">
        <img class="d-block w-100"
             src="${base}/${encodeURIComponent(name)}"
             alt="${name}"
             loading="lazy"
             style="object-fit:contain; background:transparent; max-height:520px;">
      </div>`).join('');

    el.innerHTML = `
      <div id="${id}" class="carousel slide" data-bs-ride="carousel">
        <div class="carousel-inner">${inner}</div>
        <button class="carousel-control-prev" type="button" data-bs-target="#${id}" data-bs-slide="prev">
          <span class="carousel-control-prev-icon" aria-hidden="true"></span>
          <span class="visually-hidden">Previous</span>
        </button>
        <button class="carousel-control-next" type="button" data-bs-target="#${id}" data-bs-slide="next">
          <span class="carousel-control-next-icon" aria-hidden="true"></span>
          <span class="visually-hidden">Next</span>
        </button>
      </div>`;
  }

  async function fetchList(folder) {
    const url = `${encPath(folder)}/_list.json`;
    const res = await fetch(url, { cache: 'no-store' });
    if (!res.ok) throw new Error(`Missing _list.json at ${url}`);
    const txt = stripBOM(await res.text());
    const list = JSON.parse(txt);
    return Array.isArray(list) ? list : [];
  }

  async function initOne(el) {
    const folder = el.dataset.folder;
    if (!folder) {
      el.innerHTML = `<div class="text-muted">Missing <code>data-folder</code></div>`;
      return;
    }

    // IMPORTANT: show something immediately so you can see the script is running
    el.innerHTML = `<div class="text-muted">Loading gallery…</div>`;

    try {
      const list = await fetchList(folder);

      if (!list.length) {
        el.innerHTML = `<div class="text-muted">No images found in <code>${folder}</code></div>`;
        return;
      }

      buildCarousel(el, folder, list);
    } catch (e) {
      el.innerHTML = `
        <div class="text-muted">
          Gallery could not load automatically.<br>
          <small>
            Check that <code>${folder}/_list.json</code> exists and opens in your browser.<br>
            Also ensure you’re not using <code>file://</code>.
          </small>
        </div>`;
      console.warn('[auto-gallery] failed:', e);
    }
  }

  function boot() {
    document.querySelectorAll('#auto-gallery, .auto-gallery').forEach(initOne);
  }

  // Works even if script loads after DOMContentLoaded
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();
